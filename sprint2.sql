  CREATE OR REPLACE NONEDITIONABLE PROCEDURE "SP_CREAR_ODONTOLOGO_VINCULADO" (
    p_accion                IN VARCHAR2,        -- 'VINCULAR' o 'CREAR_USUARIO'
    p_id_usuario            IN NUMBER,
    p_nombre_completo       IN VARCHAR2,
    p_nombre_usuario        IN VARCHAR2,
    p_correo_usuario        IN VARCHAR2,
    p_password_hash         IN VARCHAR2,
    p_rol                   IN VARCHAR2,
    p_nombres               IN VARCHAR2,
    p_apellidos             IN VARCHAR2,
    p_numero_colegiado      IN VARCHAR2,
    p_especialidad          IN VARCHAR2,
    p_telefono              IN VARCHAR2,
    p_correo                IN VARCHAR2,
    p_id_odontologo         OUT NUMBER
) IS
    v_id_usuario NUMBER := p_id_usuario;
    v_count      NUMBER;
BEGIN
    IF UPPER(TRIM(p_accion)) = 'CREAR_USUARIO' THEN
        -- Verificar duplicados básicos
        SELECT COUNT(*) INTO v_count FROM usuarios WHERE LOWER(TRIM(correo)) = LOWER(TRIM(p_correo_usuario));
        IF v_count > 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Ya existe un usuario con ese correo electrónico.');
        END IF;
        SELECT COUNT(*) INTO v_count FROM usuarios WHERE LOWER(TRIM(nombre_usuario)) = LOWER(TRIM(p_nombre_usuario));
        IF v_count > 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Ya existe un usuario con ese nombre de usuario.');
        END IF;

        INSERT INTO usuarios (nombre_completo, nombre_usuario, correo, password, activo, fecha_creacion, fecha_modificacion, rol, intentos_fallidos)
        VALUES (TRIM(p_nombre_completo), TRIM(p_nombre_usuario), TRIM(p_correo_usuario), p_password_hash, 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, UNISTR('Odont\00F3logo'), 0)
        RETURNING id_usuario INTO v_id_usuario;
    ELSE
        -- VINCULAR: validar que el usuario existe, tiene rol Odontólogo y no tiene odontólogo
        IF v_id_usuario IS NULL THEN
            RAISE_APPLICATION_ERROR(-20003, 'Debe seleccionar un usuario para vincular.');
        END IF;
        SELECT COUNT(*) INTO v_count FROM usuarios WHERE id_usuario = v_id_usuario;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'El usuario seleccionado no existe.');
        END IF;
        SELECT COUNT(*) INTO v_count
          FROM usuarios
         WHERE id_usuario = v_id_usuario
           AND UPPER(TRIM(rol)) IN (UPPER(UNISTR('Odont\00F3logo')), 'ODONTOLOGO');
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20006, 'El usuario seleccionado no tiene rol Odontologo.');
        END IF;
        SELECT COUNT(*) INTO v_count FROM odontologos WHERE id_usuario = v_id_usuario;
        IF v_count > 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'El usuario seleccionado ya tiene un odontólogo asignado.');
        END IF;
    END IF;

    -- Crear odontólogo
    INSERT INTO odontologos (id_usuario, nombres, apellidos, numero_colegiado, especialidad, telefono, correo, activo, fecha_creacion, fecha_modificacion)
    VALUES (v_id_usuario, TRIM(p_nombres), TRIM(p_apellidos), TRIM(p_numero_colegiado), TRIM(p_especialidad), TRIM(p_telefono), TRIM(p_correo), 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
    RETURNING id_odontologo INTO p_id_odontologo;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END sp_crear_odontologo_vinculado;
