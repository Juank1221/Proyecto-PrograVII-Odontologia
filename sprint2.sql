    p_id_rol      IN NUMBER,
    p_nombre_rol  IN VARCHAR2,
    p_descripcion IN VARCHAR2,
    p_activo      IN NUMBER
) AS
    v_cantidad NUMBER;
BEGIN
    IF p_nombre_rol IS NULL OR TRIM(p_nombre_rol) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'El nombre del rol es obligatorio.');
    END IF;

    IF p_activo NOT IN (0, 1) OR p_activo IS NULL THEN
        RAISE_APPLICATION_ERROR(-20002, 'El estado debe ser 1 (activo) o 0 (inactivo).');
    END IF;

    SELECT COUNT(*)
      INTO v_cantidad
      FROM roles
     WHERE UPPER(TRIM(nombre_rol)) = UPPER(TRIM(p_nombre_rol))
       AND id_rol <> p_id_rol;

    IF v_cantidad > 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Ya existe otro rol con ese nombre.');
    END IF;

    UPDATE roles
       SET nombre_rol  = TRIM(p_nombre_rol),
           descripcion = TRIM(p_descripcion),
           activo      = p_activo
     WHERE id_rol = p_id_rol;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'El rol indicado no existe.');
    END IF;
END sp_actualizar_rol;
