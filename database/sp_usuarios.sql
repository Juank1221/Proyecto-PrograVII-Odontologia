-- ============================================================================
-- HU-18 / Login - Procedimientos almacenados de usuarios y autenticación
-- Oracle XE 21c / Oracle Database 19c+
--
-- Este script es idempotente: se puede ejecutar varias veces sobre el mismo
-- esquema. Crea/actualiza la tabla USUARIOS, la tabla de solicitudes de
-- recuperación y los procedimientos almacenados independientes con TODAS las
-- operaciones de datos.
--
-- La API ya no ejecuta SQL directo: únicamente invoca estos procedimientos.
-- El hash de contraseña se calcula con BCrypt en C# (Oracle no implementa
-- BCrypt de forma nativa) y los procedimientos solo persisten el hash.
--
-- Si el esquema tenía el paquete anterior PKG_USUARIOS, el script lo elimina
-- al final para evitar objetos duplicados.
--
-- Ejecutar con un usuario que tenga permisos CREATE TABLE y CREATE PROCEDURE.
-- ============================================================================

SET DEFINE OFF
SET SERVEROUTPUT ON

-- ---------------------------------------------------------------------------
-- 1. Tabla USUARIOS (solo se crea si no existe)
-- ---------------------------------------------------------------------------
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM user_tables
     WHERE table_name = 'USUARIOS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE usuarios (
                id_usuario          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre_completo     VARCHAR2(150) NOT NULL,
                nombre_usuario      VARCHAR2(50)  NOT NULL,
                correo              VARCHAR2(150) NOT NULL,
                password            VARCHAR2(255) NOT NULL,
                rol                 VARCHAR2(50)  DEFAULT 'Odontologo' NOT NULL,
                activo              NUMBER(1)     DEFAULT 1 NOT NULL,
                fecha_creacion      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
                fecha_modificacion  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
                intentos_fallidos   NUMBER(3)     DEFAULT 0 NOT NULL,
                bloqueado_hasta     TIMESTAMP,
                ultimo_acceso       TIMESTAMP,
                CONSTRAINT uq_usuarios_correo UNIQUE (correo),
                CONSTRAINT uq_usuarios_nombre_usuario UNIQUE (nombre_usuario),
                CONSTRAINT chk_usuarios_activo CHECK (activo IN (0, 1))
            )
        ]';
    END IF;
END;
/

-- ---------------------------------------------------------------------------
-- 2. Columnas nuevas para instalaciones existentes (idempotente)
-- ---------------------------------------------------------------------------
DECLARE
    v_count NUMBER;

    PROCEDURE agregar_columna(p_columna VARCHAR2, p_ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM user_tab_columns
         WHERE table_name = 'USUARIOS'
           AND column_name = p_columna;

        IF v_count = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
            DBMS_OUTPUT.PUT_LINE('Columna agregada: ' || p_columna);
        END IF;
    END;
BEGIN
    agregar_columna('ROL', 'ALTER TABLE usuarios ADD (rol VARCHAR2(50) DEFAULT ''Odontologo'' NOT NULL)');
    agregar_columna('FECHA_CREACION', 'ALTER TABLE usuarios ADD (fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)');
    agregar_columna('FECHA_MODIFICACION', 'ALTER TABLE usuarios ADD (fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)');
    agregar_columna('INTENTOS_FALLIDOS', 'ALTER TABLE usuarios ADD (intentos_fallidos NUMBER(3) DEFAULT 0 NOT NULL)');
    agregar_columna('BLOQUEADO_HASTA', 'ALTER TABLE usuarios ADD (bloqueado_hasta TIMESTAMP)');
    agregar_columna('ULTIMO_ACCESO', 'ALTER TABLE usuarios ADD (ultimo_acceso TIMESTAMP)');
END;
/

-- ---------------------------------------------------------------------------
-- 3. Tabla de solicitudes de recuperación de contraseña
-- ---------------------------------------------------------------------------
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM user_tables
     WHERE table_name = 'SOLICITUDES_PASSWORD';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE solicitudes_password (
                id_solicitud      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                id_usuario        NUMBER NOT NULL,
                correo            VARCHAR2(150) NOT NULL,
                token_hash        RAW(32) NOT NULL,
                fecha_solicitud   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                fecha_expiracion  TIMESTAMP NOT NULL,
                usado             NUMBER(1) DEFAULT 0 NOT NULL,
                fecha_uso         TIMESTAMP,
                CONSTRAINT fk_solicitudes_usuario
                    FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
                CONSTRAINT ck_solicitudes_usado CHECK (usado IN (0, 1))
            )
        ]';
        DBMS_OUTPUT.PUT_LINE('Tabla creada: SOLICITUDES_PASSWORD');
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM user_indexes
     WHERE index_name = 'IX_SOLICITUDES_TOKEN';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX ix_solicitudes_token ON solicitudes_password(token_hash)';
    END IF;
END;
/

-- ---------------------------------------------------------------------------
-- 4. Procedimientos de mantenimiento de usuarios
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_listar_usuarios(
    p_cursor OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN p_cursor FOR
        SELECT id_usuario,
               nombre_completo,
               nombre_usuario,
               correo,
               rol,
               activo
          FROM usuarios
         ORDER BY id_usuario;
END sp_listar_usuarios;
/

CREATE OR REPLACE PROCEDURE sp_obtener_usuario(
    p_id_usuario IN NUMBER,
    p_cursor     OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN p_cursor FOR
        SELECT id_usuario,
               nombre_completo,
               nombre_usuario,
               correo,
               rol,
               activo
          FROM usuarios
         WHERE id_usuario = p_id_usuario;
END sp_obtener_usuario;
/

CREATE OR REPLACE PROCEDURE sp_insertar_usuario(
    p_nombre_completo IN VARCHAR2,
    p_nombre_usuario  IN VARCHAR2,
    p_correo          IN VARCHAR2,
    p_password        IN VARCHAR2,
    p_rol             IN VARCHAR2,
    p_id_usuario      OUT NUMBER
) IS
BEGIN
    INSERT INTO usuarios (
        nombre_completo,
        nombre_usuario,
        correo,
        password,
        rol,
        activo
    ) VALUES (
        TRIM(p_nombre_completo),
        TRIM(p_nombre_usuario),
        TRIM(p_correo),
        p_password,
        NVL(TRIM(p_rol), 'Odontologo'),
        1
    )
    RETURNING id_usuario INTO p_id_usuario;
END sp_insertar_usuario;
/

CREATE OR REPLACE PROCEDURE sp_actualizar_usuario(
    p_id_usuario      IN NUMBER,
    p_nombre_completo IN VARCHAR2,
    p_nombre_usuario  IN VARCHAR2,
    p_correo          IN VARCHAR2,
    p_password        IN VARCHAR2,
    p_rol             IN VARCHAR2,
    p_activo          IN NUMBER,
    p_filas           OUT NUMBER
) IS
BEGIN
    UPDATE usuarios
       SET nombre_completo    = TRIM(p_nombre_completo),
           nombre_usuario     = TRIM(p_nombre_usuario),
           correo             = TRIM(p_correo),
           password           = NVL(p_password, password),
           rol                = NVL(TRIM(p_rol), rol),
           activo             = NVL(p_activo, activo),
           fecha_modificacion = CURRENT_TIMESTAMP
     WHERE id_usuario = p_id_usuario;

    p_filas := SQL%ROWCOUNT;
END sp_actualizar_usuario;
/

CREATE OR REPLACE PROCEDURE sp_desactivar_usuario(
    p_id_usuario IN NUMBER,
    p_filas      OUT NUMBER
) IS
BEGIN
    UPDATE usuarios
       SET activo             = 0,
           fecha_modificacion = CURRENT_TIMESTAMP
     WHERE id_usuario = p_id_usuario;

    p_filas := SQL%ROWCOUNT;
END sp_desactivar_usuario;
/

CREATE OR REPLACE PROCEDURE sp_activar_usuario(
    p_id_usuario IN NUMBER,
    p_filas      OUT NUMBER
) IS
BEGIN
    UPDATE usuarios
       SET activo             = 1,
           intentos_fallidos  = 0,
           bloqueado_hasta    = NULL,
           fecha_modificacion = CURRENT_TIMESTAMP
     WHERE id_usuario = p_id_usuario;

    p_filas := SQL%ROWCOUNT;
END sp_activar_usuario;
/

-- ---------------------------------------------------------------------------
-- 5. Procedimientos de autenticación
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_obtener_credenciales(
    p_identificador IN VARCHAR2,
    p_cursor        OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN p_cursor FOR
        SELECT id_usuario,
               nombre_completo,
               nombre_usuario,
               correo,
               rol,
               activo,
               password,
               NVL(intentos_fallidos, 0) AS intentos_fallidos,
               CASE
                   WHEN bloqueado_hasta IS NOT NULL
                        AND bloqueado_hasta > SYSTIMESTAMP
                   THEN CEIL(
                       (CAST(bloqueado_hasta AS DATE) - CAST(SYSTIMESTAMP AS DATE))
                       * 86400)
                   ELSE 0
               END AS segundos_bloqueo
          FROM usuarios
         WHERE LOWER(nombre_usuario) = LOWER(TRIM(p_identificador))
            OR LOWER(correo) = LOWER(TRIM(p_identificador))
         ORDER BY CASE
                      WHEN LOWER(nombre_usuario) = LOWER(TRIM(p_identificador))
                      THEN 0 ELSE 1
                  END
         FETCH FIRST 1 ROW ONLY;
END sp_obtener_credenciales;
/

CREATE OR REPLACE PROCEDURE sp_registrar_intento_fallido(
    p_id_usuario       IN NUMBER,
    p_max_intentos     IN NUMBER,
    p_minutos_bloqueo  IN NUMBER,
    p_intentos         OUT NUMBER,
    p_segundos_bloqueo OUT NUMBER
) IS
    v_intentos  NUMBER;
    v_bloqueado TIMESTAMP;
    v_max       NUMBER := NVL(p_max_intentos, 5);
    v_minutos   NUMBER := NVL(p_minutos_bloqueo, 15);
BEGIN
    SELECT NVL(intentos_fallidos, 0),
           bloqueado_hasta
      INTO v_intentos,
           v_bloqueado
      FROM usuarios
     WHERE id_usuario = p_id_usuario
       FOR UPDATE;

    -- Si el bloqueo anterior ya expiró, se reinicia el contador.
    IF v_bloqueado IS NOT NULL AND v_bloqueado <= SYSTIMESTAMP THEN
        v_intentos := 0;
    END IF;

    v_intentos := v_intentos + 1;

    IF v_intentos >= v_max THEN
        v_bloqueado := SYSTIMESTAMP + NUMTODSINTERVAL(v_minutos, 'MINUTE');
        p_segundos_bloqueo := v_minutos * 60;
    ELSE
        v_bloqueado := NULL;
        p_segundos_bloqueo := 0;
    END IF;

    UPDATE usuarios
       SET intentos_fallidos  = v_intentos,
           bloqueado_hasta    = v_bloqueado,
           fecha_modificacion = CURRENT_TIMESTAMP
     WHERE id_usuario = p_id_usuario;

    p_intentos := v_intentos;
END sp_registrar_intento_fallido;
/

CREATE OR REPLACE PROCEDURE sp_registrar_acceso(
    p_id_usuario IN NUMBER
) IS
BEGIN
    UPDATE usuarios
       SET intentos_fallidos  = 0,
           bloqueado_hasta    = NULL,
           ultimo_acceso      = SYSTIMESTAMP,
           fecha_modificacion = CURRENT_TIMESTAMP
     WHERE id_usuario = p_id_usuario;
END sp_registrar_acceso;
/

-- ---------------------------------------------------------------------------
-- 6. Procedimientos de recuperación de contraseña
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_solicitar_recuperacion(
    p_correo           IN VARCHAR2,
    p_token            IN VARCHAR2,
    p_minutos_vigencia IN NUMBER,
    p_existe           OUT NUMBER
) IS
    v_id_usuario NUMBER;
BEGIN
    p_existe := 0;

    BEGIN
        SELECT id_usuario
          INTO v_id_usuario
          FROM usuarios
         WHERE LOWER(correo) = LOWER(TRIM(p_correo))
           AND activo = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN;
    END;

    -- Se invalida cualquier solicitud anterior pendiente del usuario.
    UPDATE solicitudes_password
       SET usado = 1,
           fecha_uso = SYSTIMESTAMP
     WHERE id_usuario = v_id_usuario
       AND usado = 0;

    INSERT INTO solicitudes_password (
        id_usuario,
        correo,
        token_hash,
        fecha_solicitud,
        fecha_expiracion,
        usado
    ) VALUES (
        v_id_usuario,
        LOWER(TRIM(p_correo)),
        STANDARD_HASH(p_token, 'SHA256'),
        SYSTIMESTAMP,
        SYSTIMESTAMP + NUMTODSINTERVAL(NVL(p_minutos_vigencia, 30), 'MINUTE'),
        0
    );

    p_existe := 1;
END sp_solicitar_recuperacion;
/

CREATE OR REPLACE PROCEDURE sp_restablecer_password(
    p_token         IN VARCHAR2,
    p_password_hash IN VARCHAR2,
    p_resultado     OUT NUMBER
) IS
    v_id_solicitud NUMBER;
    v_id_usuario   NUMBER;
BEGIN
    SELECT id_solicitud,
           id_usuario
      INTO v_id_solicitud,
           v_id_usuario
      FROM solicitudes_password
     WHERE token_hash = STANDARD_HASH(p_token, 'SHA256')
       AND usado = 0
       AND fecha_expiracion > SYSTIMESTAMP
       AND ROWNUM = 1
       FOR UPDATE;

    UPDATE usuarios
       SET password           = p_password_hash,
           intentos_fallidos  = 0,
           bloqueado_hasta    = NULL,
           fecha_modificacion = CURRENT_TIMESTAMP
     WHERE id_usuario = v_id_usuario;

    UPDATE solicitudes_password
       SET usado = 1,
           fecha_uso = SYSTIMESTAMP
     WHERE id_solicitud = v_id_solicitud;

    p_resultado := 0;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_resultado := 1;
END sp_restablecer_password;
/

COMMIT;

